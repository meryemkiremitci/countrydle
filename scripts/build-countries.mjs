// Builds src/data/countries.json from open data sources (no API key needed):
//  - mledoze/countries: names, capital, region, coordinates, languages...
//  - World Bank: latest population figures
// The result is bundled with both the frontend and the API function.
// Run with: npm run build:countries
import { writeFileSync } from 'node:fs';

const [raw, wb] = await Promise.all([
  fetch('https://raw.githubusercontent.com/mledoze/countries/master/countries.json').then((r) => r.json()),
  fetch('https://api.worldbank.org/v2/country/all/indicator/SP.POP.TOTL?format=json&mrnev=1&per_page=400').then((r) =>
    r.json(),
  ),
]);
const population = new Map(wb[1].map((row) => [row.countryiso3code, row.value]));

const countries = raw
  .filter((c) => c.independent || c.unMember)
  .map((c) => ({
    name: c.name.common,
    official: c.name.official,
    trName: c.translations?.tur?.common || null,
    cca2: c.cca2,
    ccn3: c.ccn3 || null,
    capital: c.capital?.[0] || null,
    population: population.get(c.cca3) ?? null,
    area: c.area,
    region: c.region,
    subregion: c.subregion || null,
    latlng: c.latlng,
    flag: c.flag,
    languages: Object.values(c.languages || {}),
    currencies: Object.values(c.currencies || {}).map((x) => (x.symbol ? `${x.name} (${x.symbol})` : x.name)),
    altSpellings: (c.altSpellings || []).filter((s) => s.length > 2),
  }))
  .sort((x, y) => x.name.localeCompare(y.name));

writeFileSync(new URL('../src/data/countries.json', import.meta.url), JSON.stringify(countries));
// The API function only needs the names (files starting with "_" are not deployed as endpoints).
writeFileSync(
  new URL('../api/_countries.js', import.meta.url),
  `// Generated by scripts/build-countries.mjs — do not edit.\nexport const COUNTRY_NAMES = ${JSON.stringify(
    countries.map((c) => c.name),
  )};\n`,
);
console.log(`Wrote ${countries.length} countries`);
